namespace SLC_SM_RT_AddServiceItem
{
	using System;

	using Skyline.DataMiner.Automation;
	using Skyline.DataMiner.Utils.ServiceManagement.Testing.Reporting;
	using Skyline.DataMiner.Utils.ServiceManagement.Testing.Tests;

	using SLC_SM_RT_AddServiceItem.TestCases;

	/// <summary>
	/// Regression test for "SLC_SM_AS_AddServiceItem".
	/// Adds a service item to a Service Specification and verifies its type and label.
	/// </summary>
	public class Script
	{
		/// <summary>
		/// The Automation script this regression test verifies.
		/// </summary>
		public const string ScriptUnderTest = "SLC_SM_AS_AddServiceItem";

		/// <summary>
		/// The service item type requested from the script under test.
		/// </summary>
		public const string ServiceItemType = "Service";

		private const string TestArea = "ServiceCatalog";
		private const string TestName = "AddServiceItem";
		private const string TestDescription = "Verifies a service item can be added to a Service Specification with the requested type and label.";

		/// <summary>
		/// Entry point.
		/// </summary>
		/// <param name="engine">Link with SLAutomation process.</param>
		public void Run(IEngine engine)
		{
			try
			{
				RunSafe(engine);
			}
			catch (ScriptAbortException)
			{
				throw;
			}
			catch (ScriptForceAbortException)
			{
				throw;
			}
			catch (ScriptTimeoutException)
			{
				throw;
			}
			catch (Exception ex)
			{
				engine.ExitFail("Run|Something went wrong: " + ex);
			}
		}

		private static void RunSafe(IEngine engine)
		{
			var testData = new AddServiceItemTestData(engine);

			var test = new Test(engine, TestTools.GenerateTestName(TestArea, TestName), TestDescription)
			{
				// The test report is returned as JSON in the "report" script output. The QAPortal element that
				// launches this script picks it up and uploads it to the QA Portal. Failed test cases are recorded
				// in that report, so the script itself always ends successfully.
				PublishingMode = ReportPublishingMode.QaPortalScriptOutput,
				FailScriptOnFailure = false,
			};

			test.AddTestCase(
				new CreateFixturesTestCase(testData),
				new AddServiceItemTestCase(testData),
				new ValidateAddedServiceItemTestCase(testData));

			test.Run();
		}
	}
}
